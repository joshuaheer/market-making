"""
Run every experiment, regenerate every figure, and write RESULTS.md.

    python -m experiments.run_all           # full run, under a minute
    python -m experiments.run_all --quick   # fewer simulations, a few seconds
"""

import argparse
import time

from experiments import _style as st
from experiments import adverse_selection, replication, risk_frontier, volatility


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()
    start = time.time()
    print("1/4 replication");       rep = replication.run(args.quick)
    print("2/4 risk frontier");     rf = risk_frontier.run(args.quick)
    print("3/4 adverse selection"); adv = adverse_selection.run(args.quick)
    print("4/4 volatility");        vol = volatility.run(args.quick)

    L = ["# Results", "", f"Generated by `python -m experiments.run_all{' --quick' if args.quick else ''}`.", ""]

    L += ["## 1. Reproducing Avellaneda & Stoikov (2008), Table 1", "",
          f"{rep['n_sims']:,} simulated sessions per row. Each cell shows **ours (paper)**; the paper used 1,000 sessions.",
          "", replication.table_markdown(rep["rows"]), "", f"![](figures/{rep['figure']})", ""]

    L += ["## 2. Risk-return frontier", "", "| gamma | Spread | Inventory: mean | std | Sharpe | Symmetric: mean | std | Sharpe |",
          "|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rf["rows"]:
        i, s = r["inv"], r["sym"]
        L.append(f"| {r['gamma']:g} | {i['avg_spread']:.2f} | {i['mean_pnl']:.1f} | {i['std_pnl']:.1f} | {i['sharpe']:.1f} | "
                 f"{s['mean_pnl']:.1f} | {s['std_pnl']:.1f} | {s['sharpe']:.1f} |")
    L += ["", f"![](figures/{rf['figure']})", ""]

    L += [f"## 3. Adverse selection (informed traders know a ${adv['jump']:g} jump)", "",
          "| Informed per session | Unaware P&L | Filter P&L | Best fixed widening P&L | Best widening | Filter's avg widening | Informed fills (unaware / filter) |",
          "|---:|---:|---:|---:|---:|---:|---:|"]
    for r in adv["rows"]:
        L.append(f"| {r['rate']} | {r['naive']['mean_pnl']:+.1f} | {r['filter']['mean_pnl']:+.1f} | {r['best']['mean_pnl']:+.1f} | "
                 f"{r['best_extra']:.3f} | {r['filter_avg_extra']:.2f} | {r['naive']['informed_fills']:.1f} / {r['filter']['informed_fills']:.1f} |")
    focus = next(r for r in adv["rows"] if r["rate"] == adv["focus_rate"])
    L += ["", f"P&L decomposition at {adv['focus_rate']} informed traders per session (mean $ per session):", "",
          "| | Spread capture | Inventory P&L (diffusion) | Inventory P&L (jumps) | Total | Std |", "|---|---:|---:|---:|---:|---:|"]
    for key, name in (("naive", "Unaware"), ("filter", "With filter"), ("best", "Best fixed widening")):
        s = focus[key]
        L.append(f"| {name} | {s['spread_capture']:+.1f} | {s['inventory_pnl_diffusion']:+.1f} | {s['inventory_pnl_jump']:+.1f} | "
                 f"{s['mean_pnl']:+.1f} | {s['std_pnl']:.1f} |")
    L += ["", f"![](figures/{adv['figure']})", ""]

    L += ["## 4. Volatility", "", "Part A: the quoting model knows the true vol.", "",
          "| True sigma | Spread | Fills | Mean P&L | Std | Sharpe | Std(final q) |", "|---:|---:|---:|---:|---:|---:|---:|"]
    L += [f"| {r['sigma']} | {r['avg_spread']:.2f} | {r['fills']:.0f} | {r['mean_pnl']:.1f} | {r['std_pnl']:.1f} | "
          f"{r['sharpe']:.1f} | {r['std_final_q']:.2f} |" for r in vol["part_a"]]
    L += ["", f"Part B: true sigma = {vol['true_for_b']}, the quoting model assumes a different value.", "",
          "| Assumed sigma | Spread | Mean P&L | Std | Sharpe | Std(final q) |", "|---:|---:|---:|---:|---:|---:|"]
    L += [f"| {r['assumed']} | {r['avg_spread']:.2f} | {r['mean_pnl']:.1f} | {r['std_pnl']:.1f} | {r['sharpe']:.1f} | "
          f"{r['std_final_q']:.2f} |" for r in vol["part_b"]]
    L += ["", f"![](figures/{vol['figure']})", ""]

    (st.ROOT / "RESULTS.md").write_text("\n".join(L))
    print(f"done in {time.time() - start:.0f}s -> RESULTS.md and figures/")


if __name__ == "__main__":
    main()
